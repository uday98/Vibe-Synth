// Offline embedding distillation. Run on a dev machine, never in the browser.
//
// Idea: instead of shipping a ~25 MB embedding model to every visitor, run the model
// once here over a word list and keep only what the synth needs from each word —
// a few timbre weights and modifier values. The result is a few KB of plain JS.
//
//   timbre weights   = cosine similarity between the word and each timbre's `label`
//   modifier values  = projection onto a semantic axis: cos(word, positive pole) − cos(word, negative pole)
//
// Usage:
//   npm i -D @huggingface/transformers
//   node scripts/distill-lexicon.mjs scripts/wordlist.txt
// Writes src/sound/lexicon.generated.js. Curated entries in lexicon.js always win.

import { readFileSync, writeFileSync } from 'node:fs';
import { pipeline } from '@huggingface/transformers';
import { TIMBRES } from '../src/sound/timbres.js';
import { LEXICON } from '../src/sound/lexicon.js';

const MODEL = 'Xenova/all-MiniLM-L6-v2';
const TIMBRE_MIN_SIM = 0.42;   // below this a word says nothing about the source
const AXIS_MIN = 0.06;         // ignore weak projections

const POLES = {
  bright: ['bright brilliant crisp sparkling treble', 'dark dull muffled mellow bassy'],
  grit: ['distorted gritty dirty harsh crunchy', 'clean pure smooth polished'],
  length: ['long sustained endless lingering', 'short brief staccato clipped'],
  soft: ['soft gentle slow swelling fading in', 'punchy hard sharp sudden percussive'],
  space: ['spacious reverberant cavernous distant vast', 'dry close intimate tight'],
  motion: ['wobbling pulsing evolving moving', 'static still steady frozen'],
  noise: ['noisy dusty lo-fi crackling hissing', 'clean pristine noiseless'],
  tension: ['dissonant eerie tense unsettling strange', 'consonant sweet harmonious pleasant'],
  register: ['high pitched tiny shrill', 'low pitched deep huge rumbling'],
};
const AXIS_SCALE = { register: 30 };   // semitones per unit of projection; others use 4

const cos = (a, b) => a.reduce((s, x, i) => s + x * b[i], 0);   // vectors are normalised
const round = (x) => Math.round(x * 100) / 100;

const words = readFileSync(process.argv[2] || 'scripts/wordlist.txt', 'utf8')
  .split(/\s+/).map((w) => w.trim().toLowerCase()).filter((w) => /^[a-z]{3,}$/.test(w) && !LEXICON[w]);

const embed = await pipeline('feature-extraction', MODEL);
const vec = async (texts) => (await embed(texts, { pooling: 'mean', normalize: true })).tolist();

const timbreIds = Object.keys(TIMBRES);
const timbreVecs = await vec(timbreIds.map((id) => TIMBRES[id].label));
const poleVecs = {};
for (const [axis, [pos, neg]] of Object.entries(POLES)) {
  const [p, n] = await vec([pos, neg]);
  poleVecs[axis] = { p, n };
}

const out = {};
const BATCH = 64;
for (let i = 0; i < words.length; i += BATCH) {
  const batch = words.slice(i, i + BATCH);
  const vs = await vec(batch);
  batch.forEach((w, j) => {
    const v = vs[j];
    const sims = timbreIds.map((id, k) => [id, cos(v, timbreVecs[k])]).sort((a, b) => b[1] - a[1]);
    const t = {};
    for (const [id, s] of sims.slice(0, 2)) if (s >= TIMBRE_MIN_SIM) t[id] = round(s);
    const m = {};
    for (const [axis, { p, n }] of Object.entries(poleVecs)) {
      const d = cos(v, p) - cos(v, n);
      if (Math.abs(d) >= AXIS_MIN) m[axis] = round(d * (AXIS_SCALE[axis] || 4));
    }
    if (Object.keys(t).length || Object.keys(m).length) {
      out[w] = { t: Object.keys(t).length ? t : null, m: Object.keys(m).length ? m : null };
    }
  });
  process.stdout.write(`\r${Math.min(i + BATCH, words.length)}/${words.length}`);
}

writeFileSync(
  'src/sound/lexicon.generated.js',
  `// Generated by scripts/distill-lexicon.mjs from ${MODEL}. Do not edit by hand.\n` +
  `export const GENERATED = ${JSON.stringify(out)};\n`,
);
console.log(`\nwrote ${Object.keys(out).length} words`);
